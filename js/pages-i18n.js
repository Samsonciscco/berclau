/* ---------- Fusion + réapplication de la langue ---------- */
document.addEventListener('DOMContentLoaded', () => {
  // Fusionner les traductions des pages dans window.translations
  Object.keys(window.pagesTranslations).forEach(lang => {
    if (window.translations && window.translations[lang]) {
      Object.assign(window.translations[lang], window.pagesTranslations[lang]);
    }
  });

  // Réappliquer la langue active pour inclure les nouvelles clés
  const current = localStorage.getItem('lang') || 'fr';
  if (typeof window.applyLang === 'function') {
    window.applyLang(current);
  }
});